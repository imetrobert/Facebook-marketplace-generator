#!/usr/bin/env python3
"""Writes docs/code-map.md: every top-level function, class and exported constant in js/ and the Edge Function,
with line numbers, so a change can open just the range it needs. Run from the repo root: python3 scripts/code_map.py"""
import re, pathlib
FILES = sorted(pathlib.Path("js").glob("*.js")) + [pathlib.Path("supabase/functions/generate/index.ts")]
PAT = re.compile(r"^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?\s+(\w+)|class\s+(\w+)|const\s+([A-Z][A-Z0-9_]+|[a-z]\w*)\s*=\s*(?:async\s*)?(?:\(|[A-Za-z_]+\s*=>|\{|\[))")
out = ["# Code map (generated by scripts/code_map.py on every push; do not edit by hand)", "",
       "Open the file at the line you need (Read with offset/limit) instead of reading it whole.", ""]
for f in FILES:
    lines = f.read_text(encoding="utf-8").splitlines()
    rows = []
    for i, ln in enumerate(lines, 1):
        m = PAT.match(ln)
        if m:
            name = next(g for g in m.groups() if g)
            rows.append("- %s:%d  %s%s" % (f.name, i, name, "  (exported)" if ln.startswith("export") else ""))
    out += ["## %s (%d lines)" % (f, len(lines)), ""] + (rows or ["- (no top-level names found)"]) + [""]
pathlib.Path("docs/code-map.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/code-map.md (%d files)" % len(FILES))
